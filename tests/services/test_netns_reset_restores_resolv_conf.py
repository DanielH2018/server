"""A wireguard sidecar restarted after a SIGKILL resolves through the kubelet's nameserver (#8489).

The kubelet bind-mounts one resolv.conf into every container of the pod, so it outlives a
container restart. wg-quick points it at `MULLVAD_DNS` while the tunnel is up, and only the
graceful finish script takes that back out. A SIGKILLed container skips the finish script, and the
next start would look up api.mullvad.net through a resolver only the dead tunnel can reach.

No user namespace is available to mount over `/etc/resolv.conf`, so each container start runs a
copy of `netns-reset.sh` with its absolute paths moved under a sandbox root. Between starts the
sandbox keeps what is pod-scoped (the kubelet's resolv.conf and the sidecar's rendered volume
mounts) and drops the container-local rest, as a container restart does. `ip`, `iptables-restore`
and `resolvconf` are stubs; the stub `resolvconf` does nothing, because openresolv's state lives in
the container and dies with it.
"""

import os
import re
import shutil
from pathlib import Path

from _helpers import K8S_ROLES, load_yaml
from _k8s_render import rendered_docs
from lib.proc_testing import fake_bin, run

SCRIPT = K8S_ROLES / "qbittorrent/files/netns-reset.sh"
KUBELET_RESOLV = "/etc/resolv.conf"
# The Mullvad mod's resolver when MULLVAD_DNS is unset.
MULLVAD_DEFAULT_DNS = "10.64.0.1"

STUB_IP = """#!/bin/sh
case "$*" in
  "-4 route show default") cat "$STUB_DIR/main_default" ;;
  "link show wg0") [ -e "$STUB_DIR/wg0" ] || exit 1 ;;
esac
exit 0
"""


def _sidecar():
    for role, _tpl, doc in rendered_docs():
        if role == "qbittorrent" and doc["kind"] == "Deployment":
            spec = doc["spec"]["template"]["spec"]
            wg = next(c for c in spec["initContainers"] if c["name"] == "wireguard")
            return doc["metadata"]["namespace"], wg
    raise AssertionError("qbittorrent Deployment did not render")


class Pod:
    """One qbittorrent pod whose wireguard sidecar the test starts, tunnels and kills."""

    def __init__(self, tmp_path: Path):
        namespace, wg = _sidecar()
        self.env = {e["name"]: e.get("value") for e in wg["env"]}
        self.pod_paths = [m["mountPath"] for m in wg["volumeMounts"]]
        self.root = tmp_path / "root"
        self.stub_dir = tmp_path / "stub"
        self.stub_dir.mkdir()
        (self.stub_dir / "main_default").write_text("default via 10.42.1.1 dev eth0\n")
        self.nameserver = load_yaml(K8S_ROLES / "coredns/defaults/main.yml")[
            "coredns_cluster_ip"
        ]
        self.kubelet_resolv = (
            f"search {namespace}.svc.cluster.local svc.cluster.local cluster.local\n"
            f"nameserver {self.nameserver}\noptions ndots:5\n"
        )
        self.script = tmp_path / "netns-reset.sh"
        self.script.write_text(self._sandboxed(SCRIPT.read_text()))
        self.stubs = fake_bin(
            tmp_path / "bin",
            ip=STUB_IP,
            resolvconf="#!/bin/sh\ncat >/dev/null\nexit 0\n",
            **{"iptables-restore": "#!/bin/sh\ncat >/dev/null\n"},
        )
        for path in self.pod_paths:
            self._at(path).mkdir(parents=True, exist_ok=True)
        self._at(KUBELET_RESOLV).parent.mkdir(parents=True)
        self._at(KUBELET_RESOLV).write_text(self.kubelet_resolv)

    def _at(self, path: str) -> Path:
        return self.root / path.lstrip("/")

    def _sandboxed(self, text: str) -> str:
        tops = {"etc", "run", "tmp", "var"} | {
            p.strip("/").split("/")[0] for p in self.pod_paths
        }
        pattern = rf"(?<![\w./$}}-])/({'|'.join(sorted(tops))})(?=[/\s\"']|$)"
        return re.sub(pattern, lambda m: f"{self.root}/{m.group(1)}", text, flags=re.M)

    def start(self) -> None:
        env = {
            **os.environ,
            "STUB_DIR": str(self.stub_dir),
            "LAN_NETWORKS": self.env["LAN_NETWORKS"],
            "PUID": self.env["PUID"],
        }
        run(["sh", str(self.script)], env=env, stub_bin=self.stubs, check=True)

    def bring_tunnel_up(self) -> None:
        (self.stub_dir / "wg0").touch()
        dns = self.env.get("MULLVAD_DNS") or MULLVAD_DEFAULT_DNS
        self._at(KUBELET_RESOLV).write_text(
            f"# Generated by resolvconf\nnameserver {dns}\n"
        )

    def sigkill(self) -> None:
        """Drop the container-local filesystem; the netns, mounts and resolv.conf survive."""
        keep = {self._at(KUBELET_RESOLV)} | {self._at(p) for p in self.pod_paths}
        self._prune(self.root, keep)

    def _prune(self, directory: Path, keep: set[Path]) -> None:
        for child in directory.iterdir():
            if child in keep:
                continue
            if any(child in k.parents for k in keep):
                self._prune(child, keep)
            elif child.is_dir():
                shutil.rmtree(child)
            else:
                child.unlink()

    def nameservers(self) -> list[str]:
        return re.findall(
            r"^nameserver\s+(\S+)", self._at(KUBELET_RESOLV).read_text(), re.M
        )


def test_a_restart_after_a_sigkilled_tunnel_resolves_through_the_kubelets_nameserver(
    tmp_path,
):
    pod = Pod(tmp_path)
    pod.start()
    pod.bring_tunnel_up()
    pod.sigkill()
    pod.start()
    assert pod.nameservers() == [pod.nameserver], (
        f"after a SIGKILL with wg0 up, the next start must resolve through the kubelet's "
        f"nameserver {pod.nameserver}, not {MULLVAD_DEFAULT_DNS}; resolv.conf names "
        f"{pod.nameservers()}"
    )


def test_every_restart_after_a_sigkill_resolves_through_the_kubelets_nameserver(
    tmp_path,
):
    pod = Pod(tmp_path)
    pod.start()
    for restart in range(1, 4):
        pod.bring_tunnel_up()
        pod.sigkill()
        pod.start()
        assert pod.nameservers() == [pod.nameserver], (
            f"restart {restart} after a SIGKILL left resolv.conf naming "
            f"{pod.nameservers()}, not the kubelet's {pod.nameserver}"
        )
